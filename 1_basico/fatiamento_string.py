mensagem = "Olá mundo"
print(mensagem[5])
print(mensagem[-4])

# Fatiamento
# [i:f]
print(mensagem[4:])  # Se não colocar nd no fim imprime todo o resto
print(mensagem[4:8])  # Determina onde vai parar

# A função len
print(len(mensagem))  # Mostra quantos caracteres minha variavel tem (incluindo espaços)
