primeiro_valor = int(input("Digite um numero: "))
segundo_valor = int(input("Digite um segundo número: "))

if primeiro_valor > segundo_valor:
    print(f"\nO primeiro valor: {primeiro_valor} é maior que o segundo valor: {segundo_valor}")
else:
    print(f"O segundo valor: {segundo_valor} é maior do que o primeiro valor: {primeiro_valor}")