# strings são textos entre aspas
# aspas simples e duplas funcionam igualmente

"""
Preferencia pessoal:
- Aspas simples para argumentos
- Aspas duplas para texto
"""

print("Hello world!")
print('Hello world!')

# Caractere de Escape
print("Hello \"world!") # fica um código sujo, feio
print('"Hello world com aspas"') # começando o print com aspas simples, aspas duplas poderão ser impressas